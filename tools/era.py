SPAN = re.compile(r"至|以後|以前|~|－|-|—|或|、|及")
YEAR = re.compile(r"[（(]\s*(-?\d{3,4})")
# 「清高宗乾隆十一年」「明神宗萬曆」「清 乾隆」「宋徽宗宣和二年」
EMPEROR = re.compile(r"^(?:北宋|南宋|宋|元|明|清|唐|金|遼)\s*([^\s年]{1,3}?(?:宗|祖|帝))([^\s（(年元二三四五六七八九十]{2})")
REIGN_ONLY = re.compile(r"^(?:北宋|南宋|宋|元|明|清)\s+([一-鿿]{2})(?:$|\s|年|[（(])")


NEOLITHIC = re.compile(r"^[一-鿿]{1,8}?(文化|系|新石器時代)")


def match_dyn(s: str):
    for name, dyn, grp, y0, y1 in DYN:
        if s.startswith(name):
            return dyn, grp, y0, y1, name
    # 「崧澤文化」「龍山—齊家系」「松黑地區新石器時代」這類考古學文化都歸新石器時代
    m = NEOLITHIC.match(s)
    if m:
        return "新石器時代", "新石器時代", -8000, -2000, m.group(0)
    return None


def norm(era: str) -> dict:
    """回傳 {raw, dyn, group, emperor, reign, year, y0, y1, quiz, why}。why 說明為何不能出題。"""
    s = (era or "").strip().replace("　", " ")
    r = {"raw": s, "dyn": None, "group": None, "emperor": None, "reign": None, "year": None,
         "y0": None, "y1": None, "quiz": False, "why": ""}
    if not s or any(w in s for w in NONE_WORDS):
        r["why"] = "無年代"
        return r
    if s.startswith(("（傳）", "(傳)", "傳")):
        r["why"] = "傳世年代不確定"
        return r
    if any(s.startswith(f) for f in FOREIGN):
        r["why"] = "外國"
        return r
    m = match_dyn(s)
    if not m:
        r["why"] = "只寫世紀" if re.search(r"世紀|西元", s) else "對不到朝代"
        return r
    r["dyn"], r["group"], r["y0"], r["y1"], head = m
    rest = s[len(head):]
    y = YEAR.search(s)
    if y:
        r["year"] = int(y.group(1))
    e = EMPEROR.match(s)
    if e:
        r["emperor"], r["reign"] = e.group(1), e.group(2)
    else:
        ro = REIGN_ONLY.match(s)
        if ro and not match_dyn(ro.group(1)):
            r["reign"] = ro.group(1)
    # 「明晚期至清」這種跨朝：後半段還有另一個朝代就不能出題（同朝「春秋中晚期」可以）
    if SPAN.search(rest):
        tail = SPAN.split(rest, 1)[1].strip()
        other = match_dyn(tail)
        if "以後" in rest or "以前" in rest or (other and other[1] != r["group"]):
            r["why"] = "跨朝代"
            return r
    r["quiz"] = True
    return r
